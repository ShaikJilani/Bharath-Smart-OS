export function getLocalizedHelpArticles(selectedLanguage: string): HelpArticle[] {
  if (selectedLanguage === "Hindi") {
    return HINDI_HELP_ARTICLES;
  }
  if (selectedLanguage === "English" || !SECTOR_NAME_TRANSLATIONS[selectedLanguage]) {
    return ENGLISH_HELP_ARTICLES;
  }

  // For other languages, get base 5 handcrafted articles
  const base = getBaseLocalizedHelpArticles(selectedLanguage);
  
  // Create a dictionary of translated sector names to match
  const trans = SECTOR_NAME_TRANSLATIONS[selectedLanguage];
  
  // Return exactly 16 articles matching the 16 English sectors in SECTORS order
  const SECTORS = [
    "Roads and potholes",
    "Streetlights",
    "Water supply",
    "Water leakage",
    "Drainage and sewage",
    "Waste collection",
    "Illegal dumping",
    "Public toilets",
    "Air pollution",
    "Water pollution",
    "Traffic congestion",
    "Electricity issues",
    "Government building damage",
    "Public safety",
    "Agricultural problems",
    "Other civic concerns"
  ];

  return SECTORS.map((engSector) => {
    // Determine if this sector has a handcrafted base article
    let matchingBaseArticle: HelpArticle | undefined;
    if (engSector === "Roads and potholes" && base[0]) {
      matchingBaseArticle = base[0];
    } else if (engSector === "Water supply" && base[1]) {
      matchingBaseArticle = base[1];
    } else if (engSector === "Streetlights" && base[2]) {
      matchingBaseArticle = base[2];
    } else if (engSector === "Drainage and sewage" && base[3]) {
      matchingBaseArticle = base[3];
    } else if (engSector === "Waste collection" && base[4]) {
      matchingBaseArticle = base[4];
    }

    const localizedTitle = trans[engSector] || engSector;

    if (matchingBaseArticle) {
      return {
        ...matchingBaseArticle,
        sector: localizedTitle
      };
    }

    // Fall back to the English template with a translated title
    const engTemplate = ENGLISH_HELP_ARTICLES.find(a => a.sector === engSector) || ENGLISH_HELP_ARTICLES[ENGLISH_HELP_ARTICLES.length - 1];
    return {
      ...engTemplate,
      sector: localizedTitle
    };
  });
}
